'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { Script } = require('node:vm');

const root = path.resolve(__dirname, '..');
const src = path.join(root, 'src');
const modules = new Map();
function visit(filename) {
  const nam = path.relative(src, filename).replaceAll(path.sep, '/');
  if (modules.has(nam)) return nam;
  if (!filename.startsWith(src + path.sep)) throw new Error('Módulo fora da pasta src.');
  const text = fs.readFileSync(filename, 'utf8');
  modules.set(nam, '');
  if (filename.endsWith('.json')) {
    modules.set(nam, `module.exports = ${JSON.stringify(JSON.parse(text))};`);
    return nam;
  }
  const code = text.replace(/\brequire\((['"])(\.[^'"]+)\1\)/g, (_, __, target) => {
    const absolute = path.resolve(path.dirname(filename), target);
    const actual = path.extname(absolute) ? absolute : absolute + '.js';
    return `load(${JSON.stringify(visit(actual))})`;
  });
  modules.set(nam, code);
  return nam;
}
const entry = visit(path.join(src, 'main.js'));
const out = `// Generated by npm run build. Edit src/ instead.
'use strict';
module.exports = (function (require) {
  const modules = {
${[...modules].map(([name, code]) => `    ${JSON.stringify(name)}: function (module, exports, load, require) {\n${code}\n    }`).join(',\n')}
  };
  const cache = Object.create(null);
  function load(id) {
    if (cache[id]) return cache[id].exports;
    const m = cache[id] = { exports: {} };
    modules[id](m, m.exports, load, require);
    return m.exports;
  }
  return load(${JSON.stringify(entry)});
})(require);
`;
new Script(out);
fs.writeFileSync(path.join(root, 'main.js'), out);
console.log(`Basic RPG: ${modules.size} modules, ${Buffer.byteLength(out)} bytes`);
